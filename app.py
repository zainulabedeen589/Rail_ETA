"""Flask web dashboard for the Rail ETA project.

Run from the repository root with:
    python flask_app.py

This app reuses the existing src/ prediction and training pipeline.
The Streamlit application in app.py is intentionally left untouched.
"""
from __future__ import annotations

import logging
import sys
import threading
from pathlib import Path

from flask import Flask, jsonify, render_template, request, send_from_directory, abort

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from config import settings  # noqa: E402
from predictor import load_model, predict_single, format_duration  # noqa: E402

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("rail_eta.flask")

app = Flask(
    __name__,
    template_folder=str(ROOT / "templates"),
    static_folder=str(ROOT / "static"),
)
app.config["JSON_SORT_KEYS"] = False

_model = None
_model_lock = threading.Lock()
_training_lock = threading.Lock()


def get_model():
    """Load the persisted model once, then reuse it between requests."""
    global _model
    if _model is None:
        with _model_lock:
            if _model is None:
                _model = load_model(settings.model_path)
    return _model


@app.get("/")
def index():
    return render_template("index.html")


@app.get("/health")
def health():
    return jsonify({"status": "ok", "service": "rail-eta", "version": "3.0.0"})


@app.get("/api/status")
def api_status():
    exists = settings.model_path.exists()
    return jsonify({
        "status": "ok",
        "model_exists": exists,
        "model_loaded": _model is not None,
        "ready": exists,
        "model_file": settings.model_path.name,
        "model_path": str(settings.model_path),
    })


@app.post("/api/predict")
def api_predict():
    payload = request.get_json(silent=True) or {}
    try:
        distance = float(payload.get("distance", 0))
        raw_stations = float(payload.get("stations", 0))
        if distance <= 0:
            return jsonify({"error": "Distance must be greater than zero."}), 400
        if raw_stations < 1 or not raw_stations.is_integer():
            return jsonify({"error": "Stations must be a positive whole number."}), 400

        if not settings.model_path.exists():
            return jsonify({"error": "The trained model was not found. Train the model first."}), 503

        model = get_model()
        hours = predict_single(model, distance, int(raw_stations))
        return jsonify({
            "predicted_duration_hours": round(hours, 4),
            "predicted_duration_human": format_duration(hours),
            "distance": distance,
            "stations": int(raw_stations),
            "model": settings.model_path.name,
        })
    except Exception as exc:  # noqa: BLE001
        logger.exception("Prediction request failed")
        return jsonify({"error": "Unable to generate a prediction. Check the model and server logs."}), 500


@app.get("/api/metrics")
def api_metrics():
    metrics_path = settings.metrics_path
    if not metrics_path.exists():
        return jsonify({"error": "No model metrics found. Run training first."}), 404
    try:
        import json
        return jsonify(json.loads(metrics_path.read_text(encoding="utf-8")))
    except Exception:  # noqa: BLE001
        logger.exception("Could not read metrics file")
        return jsonify({"error": "Could not read model metrics."}), 500


@app.post("/api/train")
def api_train():
    """Run the repository's actual end-to-end training pipeline."""
    global _model
    if not _training_lock.acquire(blocking=False):
        return jsonify({"success": False, "error": "Training is already running."}), 409
    try:
        from pipeline import run_pipeline
        metrics = run_pipeline()
        _model = None  # force next prediction to load the newly persisted model
        best_model = metrics.get("best_model", "unknown") if isinstance(metrics, dict) else "unknown"
        return jsonify({
            "success": True,
            "message": "Training completed successfully.",
            "best_model": best_model,
        })
    except Exception:  # noqa: BLE001
        logger.exception("Training pipeline failed")
        return jsonify({
            "success": False,
            "error": "Training failed. Check the dataset and server logs.",
        }), 500
    finally:
        _training_lock.release()


@app.get("/api/visualisations")
def api_visualisations():
    """Expose the chart files generated by src/visuals.py."""
    figures_dir = settings.figures_dir
    best_model = "gradientboosting"
    if settings.metrics_path.exists():
        try:
            import json
            payload = json.loads(settings.metrics_path.read_text(encoding="utf-8"))
            best_model = payload.get("best_model") or best_model
        except Exception:  # noqa: BLE001
            logger.warning("Unable to read best model name for chart lookup")

    candidates = {
        "duration_vs_distance": "duration_vs_distance.png",
        "duration_vs_stations": "duration_vs_stations.png",
        "top_routes": "top_routes.png",
        "actual_vs_predicted": f"actual_vs_predicted_{best_model}.png",
        "residuals": f"residuals_{best_model}.png",
    }
    images = {
        key: (f"/artifacts/{filename}" if (figures_dir / filename).is_file() else None)
        for key, filename in candidates.items()
    }
    return jsonify({"best_model": best_model, "images": images})


@app.get("/artifacts/<path:filename>")
def figure_file(filename: str):
    """Serve generated figures from the configured results/figures directory."""
    if not (settings.figures_dir / filename).is_file():
        abort(404)
    return send_from_directory(settings.figures_dir, filename)


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=5001, debug=True)
