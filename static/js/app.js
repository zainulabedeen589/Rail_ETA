/* Rail ETA — frontend behaviour connected to this repository's Flask routes. */
(() => {
  "use strict";

  const API = {
    predict: "/api/predict",
    train: "/api/train",
    metrics: "/api/metrics",
    status: "/api/status",
    visualisations: "/api/visualisations"
  };
  const $ = (id) => document.getElementById(id);
  let rmseChart = null;
  let toastTimer = null;

  const showToast = (message) => {
    const toast = $("toast");
    if (!toast) return;
    toast.textContent = message;
    toast.classList.add("show");
    window.clearTimeout(toastTimer);
    toastTimer = window.setTimeout(() => toast.classList.remove("show"), 3600);
  };

  const setTab = (name) => {
    document.querySelectorAll(".tab-panel").forEach(p => p.classList.toggle("active", p.id === `tab-${name}`));
    document.querySelectorAll(".nav-item").forEach(b => b.classList.toggle("active", b.dataset.tab === name));
    const labels = {predict:"Predict journey",models:"Model performance",training:"Training centre",insights:"Data insights"};
    const titles = {predict:["Journey","prediction."],models:["Model","performance."],training:["Training","centre."],insights:["Data","insights."]};
    $("breadcrumbCurrent").textContent = labels[name];
    $("pageTitle").innerHTML = `${titles[name][0]} <span>${titles[name][1]}</span>`;
    $("pageSubtitle").textContent = ({
      predict:"Estimate journey duration with your machine-learning ensemble.",
      models:"Compare evaluation metrics from your latest training run.",
      training:"Manage the model pipeline and inspect the model family.",
      insights:"Explore the charts generated by your analytics pipeline."
    })[name];
    if (name === "models") loadMetrics();
    if (name === "insights") loadVisualisations();
    $("sidebar").classList.remove("open");
  };

  document.querySelectorAll(".nav-item").forEach(button => button.addEventListener("click", () => setTab(button.dataset.tab)));
  $("menuToggle").addEventListener("click", () => $("sidebar").classList.toggle("open"));
  $("refreshBtn").addEventListener("click", async () => {
    await Promise.allSettled([loadStatus(), loadMetrics()]);
    showToast("Dashboard data refreshed.");
  });

  const formatDuration = (hours) => {
    const totalMinutes = Math.round(Number(hours) * 60);
    const days = Math.floor(totalMinutes / 1440);
    const hrs = Math.floor((totalMinutes % 1440) / 60);
    const mins = totalMinutes % 60;
    const parts = [];
    if (days) parts.push(`${days} day${days === 1 ? "" : "s"}`);
    if (hrs) parts.push(`${hrs} hour${hrs === 1 ? "" : "s"}`);
    if (mins || !parts.length) parts.push(`${mins} min`);
    return parts.join(" ");
  };

  async function requestJSON(url, options = {}) {
    const response = await fetch(url, {
      headers: {"Accept":"application/json", ...(options.body ? {"Content-Type":"application/json"} : {})},
      ...options
    });
    const data = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(data.error || data.message || `Request failed (${response.status}).`);
    return data;
  }

  $("predictionForm").addEventListener("submit", async (event) => {
    event.preventDefault();
    const distance = Number($("distance").value);
    const stations = Number($("stations").value);
    if (!Number.isFinite(distance) || distance <= 0 || !Number.isInteger(stations) || stations < 1) {
      showToast("Enter a positive distance and a whole-number station count.");
      return;
    }
    const button = $("predictBtn");
    button.disabled = true;
    button.querySelector("span:first-child").textContent = "Calculating…";
    try {
      // Matches flask_app.py and src/predictor.py response fields.
      const data = await requestJSON(API.predict, {
        method:"POST",
        body:JSON.stringify({distance, stations})
      });
      const hours = Number(data.predicted_duration_hours);
      if (!Number.isFinite(hours) || hours < 0) throw new Error("The server returned an invalid prediction.");
      renderPrediction({
        hours,
        distance,
        stations,
        model:data.model || "rail_eta_best_model.joblib",
        formatted:data.predicted_duration_human || formatDuration(hours)
      });
      showToast("Prediction generated by the trained model.");
    } catch (error) {
      showToast(error.message || "Unable to generate prediction.");
    } finally {
      button.disabled = false;
      button.querySelector("span:first-child").textContent = "Generate prediction";
    }
  });

  function renderPrediction({hours, distance, stations, model, formatted}) {
    $("resultPlaceholder").classList.add("hidden");
    $("resultValue").classList.remove("hidden");
    $("durationHours").textContent = hours.toFixed(2);
    $("durationHuman").textContent = formatted;
    $("resultModel").textContent = model;
    $("resultDistance").textContent = `${distance.toLocaleString()} km`;
    $("resultStations").textContent = stations.toLocaleString();
    $("resultPace").textContent = `${(hours / distance * 100).toFixed(2)} hrs`;
    $("predictionStatus").textContent = "Generated";
    $("resultState").textContent = "PREDICTION READY";
  }

  async function loadStatus() {
    try {
      const data = await requestJSON(API.status);
      const ready = Boolean(data.model_exists);
      $("modelStatusDot").style.background = ready ? "#2bd49c" : "#e8b65e";
      $("modelStatusTag").textContent = ready ? "READY" : "NOT TRAINED";
      $("modelStatusTag").style.color = ready ? "#52d9ae" : "#e8b65e";
      $("modelStatusTitle").textContent = ready ? "Model is ready" : "Model not trained";
      $("modelStatusText").textContent = ready ? "Your saved model is available for inference." : "Run the training pipeline before predicting.";
      if (data.model_file) $("modelFileName").textContent = data.model_file;
    } catch (_) {
      $("modelStatusTag").textContent = "API OFFLINE";
      $("modelStatusTitle").textContent = "Backend unavailable";
      $("modelStatusText").textContent = "Unable to read the Flask model status endpoint.";
    }
  }

  async function loadMetrics() {
    try {
      const data = await requestJSON(API.metrics);
      renderMetrics(data);
    } catch (error) {
      $("bestModelMetric").textContent = "—";
      $("maeMetric").textContent = "—";
      $("rmseMetric").textContent = "—";
      $("r2Metric").textContent = "—";
    }
  }

  function renderMetrics(payload) {
    const results = payload.results || {};
    const bestKey = payload.best_model || Object.keys(results)[0];
    const best = results[bestKey] || {};
    $("bestModelMetric").textContent = bestKey ? bestKey.replaceAll("_"," ").replace(/\b\w/g, c => c.toUpperCase()) : "—";
    $("maeMetric").textContent = metricNumber(best.mae);
    $("rmseMetric").textContent = metricNumber(best.rmse);
    $("r2Metric").textContent = metricNumber(best.r2);

    const rows = Object.entries(results)
      .map(([name, value]) => ({name, ...value}))
      .filter(row => Number.isFinite(Number(row.rmse)))
      .sort((a,b) => Number(a.rmse)-Number(b.rmse));

    $("modelTableBody").innerHTML = rows.length ? rows.map((row,index) =>
      `<tr><td>${escapeHTML(titleCase(row.name))}</td><td>${metricNumber(row.mae)}</td><td>${metricNumber(row.rmse)}</td><td>${metricNumber(row.r2)}</td><td><span class="rank-pill">${index+1}</span></td></tr>`
    ).join("") : '<tr><td colspan="5" class="table-empty">No model metrics available. Run training to populate this table.</td></tr>';

    const quality = rows.slice(0,5);
    const maxRmse = Math.max(...rows.map(r => Number(r.rmse)), 0);
    $("qualityList").innerHTML = quality.length ? quality.map(row => {
      const score = maxRmse > 0 ? Math.max(5, Math.min(100, (1 - Number(row.rmse)/maxRmse)*100)) : 0;
      return `<div class="quality-row"><div class="quality-head"><span>${escapeHTML(titleCase(row.name))}</span><b>${metricNumber(row.rmse)} RMSE</b></div><div class="quality-track"><span style="width:${score}%"></span></div></div>`;
    }).join("") : '<div class="empty-line">No evaluation data loaded yet.</div>';

    const empty = $("rmseEmpty");
    if (rmseChart) rmseChart.destroy();
    if (rows.length && window.Chart) {
      empty.style.display = "none";
      rmseChart = new Chart($("rmseChart"), {
        type:"bar",
        data:{
          labels:rows.map(r => titleCase(r.name)),
          datasets:[{
            data:rows.map(r => Number(r.rmse)),
            backgroundColor:rows.map((_,i) => i === 0 ? "#416df1" : "#cbd7ff"),
            borderRadius:6,borderSkipped:false,barThickness:18
          }]
        },
        options:{
          responsive:true,maintainAspectRatio:false,indexAxis:"y",
          plugins:{legend:{display:false},tooltip:{backgroundColor:"#14233e",padding:10,displayColors:false}},
          scales:{
            x:{beginAtZero:true,grid:{color:"#eff2f7"},ticks:{color:"#9aa4b4",font:{size:9}}},
            y:{grid:{display:false},ticks:{color:"#68758b",font:{size:9}}}
          }
        }
      });
    } else {
      empty.style.display = "grid";
    }
  }

  const metricNumber = value => Number.isFinite(Number(value)) ? Number(value).toFixed(4) : "—";
  const titleCase = value => String(value).replaceAll("_"," ").replace(/\b\w/g, c => c.toUpperCase());
  const escapeHTML = value => String(value).replace(/[&<>"']/g, ch => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[ch]));

  $("trainBtn").addEventListener("click", async () => {
    const button = $("trainBtn");
    const progress = $("trainingProgress");
    const feedback = $("trainingFeedback");
    button.disabled = true;
    progress.classList.remove("hidden");
    feedback.textContent = "";
    $("trainingMessage").textContent = "Training pipeline in progress…";
    $("trainingPercent").textContent = "RUNNING";
    try {
      const data = await requestJSON(API.train, {method:"POST", body:"{}"});
      if (data.success !== true) throw new Error(data.error || "Training did not complete.");
      $("trainingMessage").textContent = data.message || "Training completed successfully.";
      $("trainingPercent").textContent = "COMPLETE";
      feedback.textContent = `✓ Training completed. Best model: ${titleCase(data.best_model || "selected model")}.`;
      showToast("Training completed successfully.");
      await Promise.allSettled([loadStatus(), loadMetrics()]);
    } catch (error) {
      $("trainingMessage").textContent = "Training request failed.";
      $("trainingPercent").textContent = "FAILED";
      feedback.textContent = error.message;
      showToast(error.message || "Training failed.");
    } finally {
      button.disabled = false;
    }
  });

  async function loadVisualisations() {
    try {
      const data = await requestJSON(API.visualisations);
      const mapping = {
        "visual-duration-distance":data.images?.duration_vs_distance,
        "visual-duration-stations":data.images?.duration_vs_stations,
        "visual-top-routes":data.images?.top_routes,
        "visual-actual-predicted":data.images?.actual_vs_predicted,
        "visual-residuals":data.images?.residuals
      };
      Object.entries(mapping).forEach(([id, src]) => {
        const container = $(id);
        if (!src) {
          container.innerHTML = "<span>Chart not generated yet. Run model training to create it.</span>";
          return;
        }
        container.innerHTML = "";
        const img = document.createElement("img");
        img.src = src;
        img.alt = "Rail ETA model visualisation";
        img.loading = "lazy";
        img.onerror = () => { container.textContent = "Chart image could not be loaded."; };
        container.appendChild(img);
      });
    } catch (_) {
      // The UI retains its chart placeholders if the endpoint is unavailable.
    }
  }

  $("todayLabel").textContent = new Intl.DateTimeFormat("en", {
    weekday:"short",day:"2-digit",month:"short",year:"numeric"
  }).format(new Date()).toUpperCase();

  loadStatus();
  loadMetrics();
})();
